export const ui: Record<Locale, UI> = { en, 'zh-tw': zhTw, 'zh-cn': zhCn, ja };

/** URL prefix for a locale: '' for English, '/zh-tw' etc. otherwise. */
export const prefix = (lang: Locale) => (lang === defaultLocale ? '' : `/${lang}`);
/** Build a localized path, e.g. localePath('ja', '/gallery/') -> '/ja/gallery/'. */
export const localePath = (lang: Locale, path = '/') => `${prefix(lang)}${path}`;
/** Swap the locale of the current pathname. */
export function switchLocalePath(pathname: string, to: Locale) {
  const rest = pathname.replace(/^\/(zh-tw|zh-cn|ja)(?=\/|$)/, '') || '/';
  return localePath(to, rest);
}
